import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const [inputDirectory, outputDirectory] = process.argv.slice(2);
if (!inputDirectory || !outputDirectory) {
	throw new Error('Usage: embed_web_assets.mjs <built UI directory> <generated directory>');
}

const contentTypes = {
	'.html': 'text/html; charset=utf-8',
	'.js': 'text/javascript; charset=utf-8',
	'.css': 'text/css; charset=utf-8',
	'.json': 'application/json; charset=utf-8',
	'.svg': 'image/svg+xml',
	'.png': 'image/png',
	'.jpg': 'image/jpeg',
	'.jpeg': 'image/jpeg',
	'.gif': 'image/gif',
	'.webp': 'image/webp',
	'.ico': 'image/x-icon',
	'.woff': 'font/woff',
	'.woff2': 'font/woff2',
	'.ttf': 'font/ttf',
	'.wasm': 'application/wasm',
};

const root = path.resolve(inputDirectory);
const assets = fs.readdirSync(root, { recursive: true, withFileTypes: true })
	.filter(entry => entry.isFile())
	.map(entry => {
		const file = path.join(entry.parentPath, entry.name);
		return {
			file: file.replaceAll('\\', '/'),
			url: '/' + path.relative(root, file).split(path.sep).map(encodeURIComponent).join('/'),
			contentType: contentTypes[path.extname(file).toLowerCase()] ?? 'application/octet-stream',
		};
	})
	.sort((left, right) => left.url < right.url ? -1 : left.url > right.url ? 1 : 0);

if (!assets.some(asset => asset.url === '/renderer.html')) {
	throw new Error('The built UI is missing renderer.html.');
}

fs.mkdirSync(outputDirectory, { recursive: true });
const resources = ['// Generated by scripts/embed_web_assets.mjs.', '#pragma code_page(65001)', '#include <windows.h>'];
const index = ['// Generated by scripts/embed_web_assets.mjs.', '#pragma once', 'constexpr EmbeddedWebAsset EmbeddedWebAssets[] = {'];
for (const [offset, asset] of assets.entries()) {
	const id = 1000 + offset;
	if (id > 65535) {
		throw new Error('Too many embedded web assets for Windows resource IDs.');
	}

	resources.push(`${id} RCDATA ${JSON.stringify(asset.file)}`);
	index.push(`    {L${JSON.stringify(asset.url)}, L${JSON.stringify(asset.contentType)}, ${id}},`);
}
index.push('};', '');

// Refresh the resource script even when only a file's contents changed.
fs.writeFileSync(path.join(outputDirectory, 'web_assets.rc'), resources.join('\n') + '\n');
const indexPath = path.join(outputDirectory, 'web_assets.h');
const indexContents = index.join('\n');
if (!fs.existsSync(indexPath) || fs.readFileSync(indexPath, 'utf8') !== indexContents) {
	fs.writeFileSync(indexPath, indexContents);
}
console.log(`Embedded ${assets.length} web assets.`);
