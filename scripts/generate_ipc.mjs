import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { generateCpp } from './ipc/cpp.mjs';
import { protocol } from '../protocol/ipc.ts';
import { settings } from '../protocol/settings.ts';
import { validateSettings } from './ipc/settings.mjs';
import { createWireNames } from './ipc/wire_names.mjs';
import { validateProtocol } from '../protocol/schema.ts';
import { generateTypescript } from './ipc/typescript.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const buildIndex = process.argv.indexOf('--build-root');
const buildRoot = buildIndex >= 0 ? process.argv[buildIndex + 1] : undefined;
if ((buildIndex >= 0 && (!buildRoot || buildRoot.startsWith('--'))) || (check && buildRoot)) {
	throw new Error('Use --check for source contracts, or --build-root <directory> for randomized build contracts.');
}

const outputRoot = buildRoot ? path.resolve(buildRoot) : root;
const banner = '// Generated by scripts/generate_ipc.mjs from protocol/.\n' + (buildRoot
	? '// Build contract: channel wire IDs are randomized for this build.\n'
	: '// Editor/test contract: CMake compiles randomized copies under build/<preset>/ipc/<configuration>/.\n');

validateProtocol(protocol);
validateSettings(settings);
const wireNames = buildRoot ? createWireNames(protocol) : new Map();
const typescript = generateTypescript(protocol, banner, wireNames, settings);
const cpp = generateCpp(protocol, banner, wireNames, settings);
const nativeBanner = '// Generated by scripts/generate_ipc.mjs from protocol/.\n' +
	'// Shared C++ declarations. Each build generates its own randomized implementation.\n';

const outputs = [
	[path.join(outputRoot, 'ui/src/ipc/ipc.generated.ts'), typescript.contract],
	[path.join(outputRoot, 'ui/src/ipc/ipc.debug.generated.ts'), typescript.debugContract],
	[path.join(root, 'src/generated/ipc_contract.h'), cpp.header.replace(banner, nativeBanner)],
];
if (buildRoot) {
	outputs.push([path.join(outputRoot, 'src/generated/ipc_contract.cc'), cpp.implementation]);
}

let stale = false;
for (const [destination, content] of outputs) {
	const existing = fs.existsSync(destination) ? fs.readFileSync(destination, 'utf8') : '';
	if (existing === content) {
		continue;
	}
	if (check) {
		console.error(`Generated IPC file needs updating: ${path.relative(root, destination)}`);
		stale = true;
	}
	else {
		fs.mkdirSync(path.dirname(destination), { recursive: true });
		fs.writeFileSync(destination, content);
	}
}
if (buildRoot) {
	fs.writeFileSync(path.join(outputRoot, 'wire-channels.json'), JSON.stringify(Object.fromEntries(wireNames), null, 2) + '\n');
}

if (stale) {
	process.exitCode = 1;
}
