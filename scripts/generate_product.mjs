import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fields = [
	'version', 'name', 'company', 'description', 'directoryName', 'installerId', 'notificationClsid',
	'appUserModelId', 'urlProtocol', 'repository', 'executable', 'installerAsset', 'webviewRuntimeUrl',
];
const versionPattern = /^\d+\.\d+\.\d+$/;
const guidPattern = /^[\da-f]{8}(?:-[\da-f]{4}){3}-[\da-f]{12}$/i;
const banner = '// Generated by scripts/generate_product.mjs from protocol/product.json.\n';

function validateChanges(changes) {
	if (!Array.isArray(changes) || !changes.length) {
		throw new Error('Each release and nested list must contain changes.');
	}

	for (const [index, change] of changes.entries()) {
		if (Array.isArray(change)) {
			if (typeof changes[index - 1] !== 'string') {
				throw new Error('A nested changelog list must follow its parent bullet.');
			}
			validateChanges(change);
		} else if (typeof change !== 'string' || !change.trim() || /[\r\n]/.test(change)) {
			throw new Error('Changelog bullets must be nonempty, single-line Markdown strings.');
		}
	}
}

function renderChanges(changes, depth = 0) {
	return changes.map(change => Array.isArray(change)
		? renderChanges(change, depth + 1)
		: `${'  '.repeat(depth)}- ${change}`).join('\n');
}

function installerString(value) {
	return `'${value.replaceAll("'", "''")}'`;
}

export function validateProduct(product) {
	if (!product || typeof product !== 'object' || Array.isArray(product) ||
		Object.keys(product).some(key => !fields.includes(key)) ||
		fields.some(key => typeof product[key] !== 'string' || !product[key].trim() || /[\x00-\x1f]/.test(product[key]))) {
		throw new Error(`Product metadata must define exactly these nonempty string fields: ${fields.join(', ')}.`);
	}
	if (!versionPattern.test(product.version) || product.version.split('.').some(part => Number(part) > 65535)) {
		throw new Error('The product version must contain three integers between 0 and 65535.');
	}
	if (!guidPattern.test(product.installerId) || !guidPattern.test(product.notificationClsid)) {
		throw new Error('Installer and notification IDs must be GUIDs without braces.');
	}
	if (!/^[\w.-]+\/[\w.-]+$/.test(product.repository) || !/^[a-z][a-z\d+.-]*$/.test(product.urlProtocol)) {
		throw new Error('Invalid GitHub repository or URL protocol.');
	}
	if ([product.executable, product.installerAsset].some(name => !/^[\w.-]+\.exe$/.test(name)) ||
		/[<>:"/\\|?*]/.test(product.directoryName) || ['.', '..'].includes(product.directoryName)) {
		throw new Error('Product filenames and directory names must be Windows basenames.');
	}
	if (new URL(product.webviewRuntimeUrl).protocol !== 'https:') {
		throw new Error('The WebView2 Runtime download URL must use HTTPS.');
	}
}

export function validateChangelog(releases, currentVersion) {
	if (!Array.isArray(releases) || !releases.length || releases[0]?.version !== currentVersion) {
		throw new Error('The first changelog entry must match the current product version.');
	}
	const versions = new Set();
	for (const release of releases) {
		if (!release || typeof release.version !== 'string' || !versionPattern.test(release.version) ||
			versions.has(release.version) || Object.keys(release).some(key => !['version', 'description', 'changes'].includes(key))) {
			throw new Error('Changelog releases must have unique versions and a changes list.');
		}
		if (release.description !== undefined &&
			(typeof release.description !== 'string' || !release.description.trim())) {
			throw new Error('Release descriptions must be nonempty Markdown strings.');
		}
		versions.add(release.version);
		validateChanges(release.changes);
	}
}

export function renderChangelog(releases) {
	return releases.map(release => `# ${release.version}\n\n${renderReleaseNotes([release], release.version).trimEnd()}`)
		.join('\n\n---\n\n') + '\n';
}

export function renderReleaseNotes(releases, version) {
	const release = releases.find(entry => entry.version === version);
	if (!release) {
		throw new Error(`No changelog entry exists for ${version}.`);
	}
	return (release.description ? release.description + '\n\n' : '') + renderChanges(release.changes) + '\n';
}

export function generateProduct(product) {
	validateProduct(product);
	const repositoryUrl = `https://github.com/${product.repository}`;
	const constants = {
		AppName: product.name,
		AppVersion: product.version,
		AppCompany: product.company,
		AppDescription: product.description,
		AppDirectoryName: product.directoryName,
		AppExecutable: product.executable,
		AppRepository: product.repository,
		AppRepositoryUrl: repositoryUrl,
		AppUrlProtocol: product.urlProtocol,
		AppUrlPrefix: `${product.urlProtocol}://`,
		InstallerAsset: product.installerAsset,
		WebViewRuntimeDownloadUrl: product.webviewRuntimeUrl,
	};
	const header = banner + '#pragma once\n' + Object.entries(constants).map(([name, value]) =>
		`inline constexpr char ${name}[] = ${JSON.stringify(value)};`).join('\n') +
		`\ninline constexpr wchar_t AppId[] = L${JSON.stringify(product.appUserModelId)};\n`;
	const typescript = banner + `export const product = ${JSON.stringify({ ...product, repositoryUrl }, null, 4)} as const;\n`;
	const definitions = {
		ProductVersion: product.version,
		ProductName: product.name,
		ProductCompany: product.company,
		ProductDescription: product.description,
		ProductDirectoryName: product.directoryName,
		ProductInstallerId: `{{${product.installerId}}`,
		ProductAppId: product.appUserModelId,
		ProductProtocol: product.urlProtocol,
		ProductRepositoryUrl: repositoryUrl,
		ProductExecutable: product.executable,
		ProductInstallerBaseName: path.basename(product.installerAsset, '.exe'),
	};
	const installer = '; Generated by scripts/generate_product.mjs from protocol/product.json.\n' +
		Object.entries(definitions).map(([name, value]) => `#define ${name} ${installerString(value)}`).join('\n') + '\n';
	return { header, typescript, installer };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const args = process.argv.slice(2);
	if (args.length && !(args.length === 1 && args[0] === '--check') &&
		!(args.length === 2 && args[0] === '--release')) {
		throw new Error('Usage: generate_product.mjs [--check | --release <version>]');
	}
	const product = JSON.parse(fs.readFileSync(path.join(root, 'protocol/product.json'), 'utf8'));
	const releases = JSON.parse(fs.readFileSync(path.join(root, 'protocol/changelog.json'), 'utf8'));
	validateProduct(product);
	validateChangelog(releases, product.version);
	if (args[0] === '--release') {
		process.stdout.write(renderReleaseNotes(releases, args[1]));
	} else {
		const generated = generateProduct(product);
		const outputs = [
			['src/generated/product.h', generated.header],
			['ui/src/product.generated.ts', generated.typescript],
			['scripts/installer/product.generated.iss', generated.installer],
			['CHANGELOG.md', renderChangelog(releases)],
		];
		for (const [filename, content] of outputs) {
			const destination = path.join(root, filename);
			const existing = fs.existsSync(destination) ? fs.readFileSync(destination, 'utf8') : '';
			if (existing === content) {
				continue;
			}
			if (args[0] === '--check') {
				console.error(`Generated product file needs updating: ${filename}`);
				process.exitCode = 1;
			} else {
				fs.mkdirSync(path.dirname(destination), { recursive: true });
				fs.writeFileSync(destination, content);
			}
		}
	}
}
